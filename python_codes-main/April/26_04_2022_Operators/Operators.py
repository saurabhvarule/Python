
x = 5
y = 3

# Arithmetic Operators

print(x + y)
print(x - y)
print(x * y)
print(x % y)
print(x / y)
print(x ** y)       #Index
print(x // y)       #flooral division

# Assignment Operators

x += y
print(x)

x -= y
print(x)

x *= y
print(x)

x /= y
print(x)

# Relational Operators - Returns boolean value.

print(x < y)
print(x <= y)
print(x > y)
print(x >= y)
print(x == y)
print(x != y)

# Logical Operator

print(x and y)
print(x or y)

# Bitwise Operators

x = 12
y = 8

print(x & y)
